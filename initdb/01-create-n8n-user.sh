#!/usr/bin/env bash
set -Eeuo pipefail

psql --set=ON_ERROR_STOP=1 \
  --username "$POSTGRES_USER" \
  --dbname "$POSTGRES_DB" <<-EOSQL
  CREATE ROLE "$N8N_DB_USER"
    WITH LOGIN
    PASSWORD '$N8N_DB_PASSWORD'
    NOSUPERUSER
    NOCREATEDB
    NOCREATEROLE
    NOREPLICATION;

  ALTER DATABASE "$POSTGRES_DB" OWNER TO "$N8N_DB_USER";
  ALTER SCHEMA public OWNER TO "$N8N_DB_USER";
  GRANT ALL ON SCHEMA public TO "$N8N_DB_USER";
EOSQL
